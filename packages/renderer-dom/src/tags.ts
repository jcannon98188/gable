/** The element namespaces the renderer creates and validates tags for: HTML, SVG (`svg` and its descendants) and MathML (`math` and its descendants). */
export type Namespace = "html" | "svg" | "mathml";

const TAGS: Record<Namespace, Record<string, true>> = { html: HTML_TAGS, svg: SVG_TAGS, mathml: MATHML_TAGS };

/** True for a tag this renderer knows in `namespace`. Custom elements (a hyphen in the name) are always allowed in HTML. */
export function isKnownTag(namespace: Namespace, tag: string): boolean {
  if (namespace === "html" && tag.includes("-")) return true;
  return Object.hasOwn(TAGS[namespace], tag);
}

/** The element map the Template language service reads: tag name to element type, per namespace. Derived from `lib.dom`. */
export interface ElementMap {
  html: HTMLElementTagNameMap;
  svg: SVGElementTagNameMap;
  mathml: MathMLElementTagNameMap;
}

/** Every known tag name, per namespace. */
export const knownTags: { readonly [N in Namespace]: readonly string[] } = {
  html: Object.keys(HTML_TAGS),
  svg: Object.keys(SVG_TAGS),
  mathml: Object.keys(MATHML_TAGS),
};
