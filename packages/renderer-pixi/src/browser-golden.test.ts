import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "vite";
import { describe, expect, it } from "vitest";
import { compareImages, decodePng, DEFAULT_TOLERANCE, encodePng, type Image } from "./golden-image.js";

// The golden-image suite (canvas/133): a few shape scenes rendered in a real headless Chromium on software GL
// (SwiftShader) and compared against stored PNGs in packages/renderer-pixi/golden/. See golden/README.md for the
// stability conditions, the tolerance and how goldens are (re)generated.
//
//   GABLE_GOLDEN=1          run the suite (opt-in; CI sets it, see .github/workflows/canvas-browser.yml)
//   GABLE_GOLDEN_UPDATE=1   write the goldens instead of comparing (implies running); `npm run golden:update`
//   GABLE_BROWSER           path to a Chromium, Edge or Chrome binary (common locations are tried otherwise)
//
// Goldens must be generated by the environment that compares them (the Linux CI runner): another OS or GPU stack
// anti-aliases differently. A local run on another platform is for development only and should not be committed.
const candidates = [
  process.env.GABLE_BROWSER,
  "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
  "C:/Program Files/Microsoft/Edge/Application/msedge.exe",
  "C:/Program Files/Google/Chrome/Application/chrome.exe",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium",
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
].filter((p): p is string => !!p);
const browser = candidates.find((p) => existsSync(p));
const update = process.env.GABLE_GOLDEN_UPDATE === "1";
const optedIn = update || process.env.GABLE_GOLDEN === "1";
if (optedIn && !browser) throw new Error("GABLE_GOLDEN is set but no Chromium was found; set GABLE_BROWSER.");

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));
const goldenDir = here("../golden");
// Actual, expected and diff images of failing scenes land here (gitignored; CI uploads it as an artifact).
const outputDir = join(goldenDir, "__output__");

async function renderScenes(): Promise<Record<string, Image>> {
  const out = (await build({
    configFile: false,
    logLevel: "silent",
    root: here("../browser-page"),
    resolve: {
      alias: [
        { find: /^@gable\/core$/, replacement: here("../../core/src/index.ts") },
        { find: /^@gable\/core\/renderer$/, replacement: here("../../core/src/renderer.ts") },
        { find: /^@gable\/renderer-dom$/, replacement: here("../../renderer-dom/src/index.ts") },
      ],
    },
    build: { write: false, minify: false, lib: { entry: here("../browser-page/golden.ts"), formats: ["iife"], name: "Page" } },
  })) as any;
  const code: string = (Array.isArray(out) ? out[0] : out).output[0].code;
  const dir = mkdtempSync(join(tmpdir(), "gable-pixi-golden-"));
  try {
    const page = join(dir, "index.html");
    writeFileSync(
      page,
      `<!doctype html><html lang="en"><head><title>Golden</title></head><body style="margin:0"><main><div id="app" style="width:160px;height:120px"></div></main><script>${code.replace(/<\/script/gi, "<\\/script")}</script></body></html>`,
    );
    const dom = execFileSync(
      browser!,
      [
        "--headless=new",
        "--no-sandbox",
        "--use-gl=angle",
        "--use-angle=swiftshader",
        "--enable-unsafe-swiftshader",
        "--force-device-scale-factor=1",
        "--hide-scrollbars",
        `--user-data-dir=${join(dir, "profile")}`,
        "--virtual-time-budget=20000",
        "--dump-dom",
        pathToFileURL(page).href,
      ],
      { encoding: "utf8", timeout: 100_000, maxBuffer: 256 * 1024 * 1024 },
    );
    const raw = /data-report="([^"]*)"/.exec(dom);
    expect(raw, `the page reported; DOM: ${dom.slice(-700)}`).not.toBeNull();
    const report = JSON.parse(raw![1]!.replace(/&quot;/g, '"').replace(/&amp;/g, "&"));
    expect(report.error).toBeUndefined();
    expect(report.errors).toEqual([]);
    const images: Record<string, Image> = {};
    for (const [name, b64] of Object.entries<string>(report.scenes)) {
      images[name] = { width: report.width, height: report.height, data: new Uint8Array(Buffer.from(b64, "base64")) };
    }
    return images;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

describe.skipIf(!optedIn)("canvas golden images", () => {
  it(update ? "writes the golden images" : "matches the golden images", { timeout: 120_000, retry: update ? 0 : 1 }, async () => {
    const images = await renderScenes();
    expect(Object.keys(images).length).toBeGreaterThan(0);

    if (update) {
      mkdirSync(goldenDir, { recursive: true });
      for (const [name, img] of Object.entries(images)) writeFileSync(join(goldenDir, `${name}.png`), encodePng(img));
      return;
    }

    const failures: string[] = [];
    for (const [name, actual] of Object.entries(images)) {
      const file = join(goldenDir, `${name}.png`);
      if (!existsSync(file)) {
        failures.push(`${name}: no golden at ${file}; generate it with \`npm run golden:update\` on the CI environment (golden/README.md)`);
        continue;
      }
      const expected = decodePng(readFileSync(file));
      const result = compareImages(expected, actual);
      if (result.ok) continue;
      mkdirSync(outputDir, { recursive: true });
      writeFileSync(join(outputDir, `${name}.actual.png`), encodePng(actual));
      writeFileSync(join(outputDir, `${name}.expected.png`), readFileSync(file));
      if (result.diff) writeFileSync(join(outputDir, `${name}.diff.png`), encodePng(result.diff));
      failures.push(
        result.sizeMismatch
          ? `${name}: size ${actual.width}x${actual.height} differs from the golden ${expected.width}x${expected.height}`
          : `${name}: ${result.differing} of ${result.total} pixels differ (tolerance: channel > ${DEFAULT_TOLERANCE.channel} counts as differing, up to ${DEFAULT_TOLERANCE.fraction * 100}% allowed); images in ${outputDir}`,
      );
    }
    expect(failures).toEqual([]);
  });
});
